// 背景推播通知（sw.js 的 push 事件）跑在 Service Worker 自己的執行環境
// 裡，完全碰不到這個分頁的 localStorage，沒辦法直接呼叫這裡的 t()。
// IndexedDB 是少數 Service Worker 跟一般分頁都讀得到的共用儲存空間，
// 所以語言一改變就順手同步寫一份進去，sw.js 收到推播時才能自己讀出
// 使用者目前的語言、把預設標題翻成對的語言（詳見 sw.js 的
// splitbillReadLangFromDB()）。失敗（例如瀏覽器擋 IndexedDB）就靜默
// 略過，不影響本來的語言切換功能。
function syncLangToServiceWorker(lang){
  try {
    const req = indexedDB.open("splitbill-prefs", 1);
    req.onupgradeneeded = () => {
      if(!req.result.objectStoreNames.contains("kv")) req.result.createObjectStore("kv");
    };
    req.onsuccess = () => {
      const db = req.result;
      try {
        const tx = db.transaction("kv", "readwrite");
        tx.objectStore("kv").put(lang, "lang");
      } catch(e){}
    };
    req.onerror = () => {};
  } catch(e){}
}
syncLangToServiceWorker(currentLang);

function getLang(){ return currentLang; }

function t(key, vars){
  const dict = I18N[currentLang] || I18N["zh-Hant"];
  let str = (dict[key] !== undefined) ? dict[key] : (I18N["zh-Hant"][key] !== undefined ? I18N["zh-Hant"][key] : key);
  if(vars){
    Object.keys(vars).forEach(k => {
      str = str.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    });
  }
  return str;
}

// root 不傳的話套用整個文件；傳一個 DOM 節點的話只套用它底下的範圍
// （例如某個 modal 剛動態插入內容之後，只重翻那一小塊，不用整頁重跑）。
function applyI18n(root){
  const scope = root || document;
  if(!scope.querySelectorAll) return;
  // 標籤裡如果還包著按鈕（例如設定頁欄位名稱旁的「i」說明鈕），只換掉文字節點，
  // 不能用 textContent 整個覆寫，不然按鈕會被一起清掉
  scope.querySelectorAll("[data-i18n]").forEach(el => {
    if(!el.firstElementChild){ el.textContent = t(el.dataset.i18n); return; }
    const txt = [...el.childNodes].find(n => n.nodeType === 3 && n.nodeValue.trim());
    if(txt) txt.nodeValue = t(el.dataset.i18n); else el.insertBefore(document.createTextNode(t(el.dataset.i18n)), el.firstChild);
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  scope.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.dataset.i18nTitle);
    if(el.hasAttribute("aria-label")) el.setAttribute("aria-label", t(el.dataset.i18nTitle));
  });
  scope.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.documentElement.setAttribute("lang", currentLang);

  // shared-ui.js 的 enhanceSelect() 會把原生 <select> 包成一個自訂的
  // 下拉「藥丸」按鈕，按鈕文字是呼叫當下讀 option.textContent 存一份快照
  // （見 selectEl._ddSync）。如果 enhanceSelect() 是在這次 applyI18n()
  // 套用翻譯之前就跑過（例如 app.js 的初始化搶在 DOMContentLoaded 前），
  // 按鈕上的文字就會停留在套用翻譯前的舊字，光更新 <option> 本身沒用，
  // 這裡要連動重新同步一次，語言切換時（setLang → applyI18n）也才會即時更新。
  scope.querySelectorAll("select").forEach(sel => {
    if(typeof sel._ddSync === "function") sel._ddSync();
  });
}

function setLang(lang){
  if(!SUPPORTED_LANGS.includes(lang) || lang === currentLang) return;
  currentLang = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch(e){}
  syncLangToServiceWorker(lang);
  applyI18n();
  document.dispatchEvent(new CustomEvent("splitbill-lang-changed", { detail: { lang } }));
  // 畫面上很多動態內容（圖表、清單、KPI 數字...）只在資料重新整理時才會
  // 重畫一次，不是每一塊都特地接了語言切換事件監聽——與其每個地方都補一份
  // 監聽器、還要擔心漏掉哪裡，切語言之後直接整頁重新整理最單純可靠，
  // 保證畫面上每一處都是用新語言重新渲染出來的，不會有殘留的舊語言文字。
  location.reload();
}

// 共用的語言下拉選單初始化——只有 about/privacy/terms/index 這幾頁還留著
// #langSwitchToggle/#langSwitchMenu 這組浮動按鈕的 HTML（currency/summary/
// settings 已經把語言設定收進「設定」頁管理，沒有這組 DOM），沒有就直接
// 跳過，不用每頁各自判斷。
const LANG_SHORT_LABELS = { "zh-Hant": "中", "ja": "日", "en": "EN" };
function initLangSwitcher(){
  const toggle = document.getElementById("langSwitchToggle");
  const menu = document.getElementById("langSwitchMenu");
  const currentLabel = document.getElementById("langSwitchCurrentLabel");
  if(!toggle || !menu) return;

  function updateUI(){
    if(currentLabel) currentLabel.textContent = LANG_SHORT_LABELS[getLang()] || getLang();
    menu.querySelectorAll(".lang-switch-option").forEach(btn=>{
      btn.classList.toggle("active", btn.dataset.lang === getLang());
    });
  }
  function closeMenu(){
    menu.classList.add("hidden");
    toggle.setAttribute("aria-expanded", "false");
  }
  toggle.addEventListener("click", (e)=>{
    e.stopPropagation();
    const willOpen = menu.classList.contains("hidden");
    menu.classList.toggle("hidden", !willOpen);
    toggle.setAttribute("aria-expanded", willOpen ? "true" : "false");
  });
  document.addEventListener("click", (e)=>{
    if(!menu.classList.contains("hidden") && !menu.contains(e.target) && e.target !== toggle) closeMenu();
  });
  menu.querySelectorAll(".lang-switch-option").forEach(btn=>{
    btn.addEventListener("click", ()=>{ setLang(btn.dataset.lang); closeMenu(); });
  });
  document.addEventListener("splitbill-lang-changed", updateUI);
  updateUI();
}

