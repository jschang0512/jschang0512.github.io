// Builds app.js from the parts in src/, joined in file-name order, then checks the result parses.
// Edit the files in src/, never app.js itself, and run:  node build.js
// The parts are pieces of one function body (the app is a single IIFE), so a part on its own is not valid JavaScript.
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const dir = path.join(__dirname, 'src');
const parts = fs.readdirSync(dir).filter((f) => /^\d\d-.+\.js$/.test(f)).sort();
const banner = '// Generated by build.js from src/ — edit src/ and run `node build.js`; do not edit this file.\n';
const out = banner + parts.map((f) => fs.readFileSync(path.join(dir, f), 'utf8')).join('');
const file = path.join(__dirname, 'app.js');
fs.writeFileSync(file, out);
execFileSync(process.execPath, ['--check', file], { stdio: 'inherit' });
console.log('app.js built from ' + parts.length + ' parts (' + Math.round(out.length / 1024) + ' KB)');
